import React, { useState } from 'react';
import { X, Copy, Check, Printer, FileText } from 'lucide-react';
import { DecisionResult } from '../types/decision';

interface ExportSummaryModalProps {
  isOpen: boolean;
  onClose: () => void;
  result: DecisionResult;
}

export const ExportSummaryModal: React.FC<ExportSummaryModalProps> = ({
  isOpen,
  onClose,
  result,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const generateMarkdown = () => {
    const { title, options, recommendation, summary, comparisonMatrix, swot, blindspots } = result;

    return `# The Tie Breaker: Decision Dossier
**Dilemma:** ${title}
**Alternatives:** ${options.join(' vs ')}
**Date:** ${new Date(result.createdAt).toLocaleDateString()}

---

## 🏆 Verdict & Recommendation
**Recommended Path:** ${recommendation.winner}
**Confidence Level:** ${recommendation.confidenceScore}%
**Verdict Headline:** "${recommendation.verdictHeadline}"

### Strategic Rationale
${recommendation.verdictReasoning}

### The Critical Tie-Breaker Factor
${recommendation.tieBreakerFactor}

### Immediate Action Plan
${recommendation.actionPlan.map((step, idx) => `${idx + 1}. [ ] ${step}`).join('\n')}

${recommendation.irreversibleRiskWarning ? `\n⚠️ **Irreversible Risk Guardrail:** ${recommendation.irreversibleRiskWarning}\n` : ''}

---

## ⚖️ Criteria Matrix Evaluation
| Criterion | Weight | ${options.join(' | ')} |
|---|---|${options.map(() => '---|').join('')}
${comparisonMatrix.criteria.map((c) => {
  const rowScores = options.map((opt) => `${comparisonMatrix.scores[opt]?.[c.id]?.score ?? '-'}/10`);
  return `| ${c.name} | ${c.weight}/10 | ${rowScores.join(' | ')} |`;
}).join('\n')}

---

## 🔍 Cognitive Blindspots & Pre-Mortem Probes
${blindspots.map((b) => `- ${b}`).join('\n')}

---
*Generated by The Tie Breaker – Intelligent Decision Matrix*
`;
  };

  const handleCopyMarkdown = async () => {
    try {
      await navigator.clipboard.writeText(generateMarkdown());
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch (e) {
      console.error(e);
    }
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 bg-slate-900/60 backdrop-blur-xs flex items-center justify-center p-4">
      <div className="bg-white rounded-3xl max-w-2xl w-full p-6 sm:p-8 shadow-2xl border border-slate-200 max-h-[90vh] flex flex-col">
        {/* Header */}
        <div className="flex items-center justify-between pb-4 border-b border-slate-100">
          <div className="flex items-center gap-2.5">
            <div className="w-9 h-9 rounded-xl bg-indigo-100 text-indigo-700 flex items-center justify-center">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-base font-extrabold text-slate-900">
                Export Decision Dossier
              </h3>
              <p className="text-xs text-slate-700">
                Share with mentors, stakeholders, or archive in your personal knowledge base
              </p>
            </div>
          </div>

          <button
            type="button"
            onClick={onClose}
            className="p-2 text-slate-400 hover:text-slate-700 rounded-xl hover:bg-slate-100 transition-colors"
            aria-label="Close dialog"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Markdown Preview */}
        <div className="my-4 flex-1 overflow-y-auto bg-slate-900 text-slate-200 p-4 rounded-2xl font-mono text-xs leading-relaxed border border-slate-800">
          <pre className="whitespace-pre-wrap">{generateMarkdown()}</pre>
        </div>

        {/* Footer Actions */}
        <div className="pt-3 border-t border-slate-100 flex items-center justify-between gap-3">
          <button
            type="button"
            onClick={handlePrint}
            className="px-4 py-2 rounded-xl text-xs font-bold text-slate-700 hover:bg-slate-100 border border-slate-200 flex items-center gap-1.5 transition-colors"
          >
            <Printer className="w-4 h-4" />
            <span>Print Dossier</span>
          </button>

          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={handleCopyMarkdown}
              className="px-5 py-2.5 rounded-xl text-xs font-bold bg-indigo-600 hover:bg-indigo-700 text-white flex items-center gap-1.5 shadow-xs transition-colors"
            >
              {copied ? <Check className="w-4 h-4 text-emerald-300" /> : <Copy className="w-4 h-4" />}
              <span>{copied ? 'Copied to Clipboard!' : 'Copy Markdown'}</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
